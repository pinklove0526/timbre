package com.jellyfish.timbre.audio;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import com.jellyfish.timbre.model.MemorySampleSource;
import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.concurrent.TimeUnit;
import java.util.stream.Stream;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.TestFactory;
import org.junit.jupiter.api.io.TempDir;

/**
 * Opt-in interoperability test against real encoders. It runs only when the system
 * property {@code timbre.interop=true} is set and {@code ffmpeg} is installed; otherwise it
 * is skipped with a message. Files are generated by ffmpeg (a different sine frequency per
 * channel, so channel-order mistakes are visible), read with {@link WavReader}, compared
 * with an independent decode by ffmpeg, then written back with {@link WavWriter} and decoded
 * by ffmpeg again. If {@code sox} is present its decode is compared informationally only.
 *
 * <p>Only {@code @TempDir} is written to; no audio device is ever touched.
 */
class ExternalToolInteropTest {

    private static final int TIMEOUT_SECONDS = 30;
    private static final String[] ENCODINGS = {"pcm_u8", "pcm_s16le", "pcm_s24le", "pcm_s32le", "pcm_f32le"};
    private static final int[] CHANNELS = {1, 2, 3, 6};
    private static final int[] RATES = {8000, 44100, 96000};

    private static boolean haveFfprobe;
    private static boolean haveSox;
    private static final Map<String, Double> MAX_DIFF = new TreeMap<>();
    private static final List<String> RAN = new ArrayList<>();
    private static final List<String> SOX_NOTES = new ArrayList<>();
    private static long startNanos;

    @TempDir
    Path dir;

    /** One generated-file scenario. */
    private record Case(String codec, int channels, int rate, String variant) {
        String name() {
            return codec + " " + channels + "ch " + rate + "Hz " + variant;
        }

        String file() {
            return codec + "-" + channels + "-" + rate + "-" + variant + ".wav";
        }
    }

    @BeforeAll
    static void preflight() {
        startNanos = System.nanoTime();
        assumeTrue("true".equals(System.getProperty("timbre.interop")),
                "interop tests are opt-in: run with -Dtimbre.interop=true");
        String ffmpeg = firstLine("ffmpeg", "-version");
        assumeTrue(ffmpeg != null, "ffmpeg not found on PATH; install it to run the interop tests");
        String ffprobe = firstLine("ffprobe", "-version");
        String sox = firstLine("sox", "--version");
        haveFfprobe = ffprobe != null;
        haveSox = sox != null;
        System.out.println("INTEROP tools: " + ffmpeg + " | " + (ffprobe == null ? "ffprobe absent" : ffprobe)
                + " | " + (sox == null ? "sox absent" : sox));
    }

    @AfterAll
    static void summary() {
        if (RAN.isEmpty()) {
            return;
        }
        System.out.println("INTEROP cases run: " + RAN.size());
        MAX_DIFF.forEach((k, v) -> System.out.println("INTEROP max difference " + k + " = " + v));
        SOX_NOTES.forEach(n -> System.out.println("INTEROP sox (informational) " + n));
        System.out.println("INTEROP total seconds: " + (System.nanoTime() - startNanos) / 1_000_000_000.0);
    }

    @TestFactory
    Stream<DynamicTest> realEncoderFiles() {
        List<Case> cases = new ArrayList<>();
        for (String codec : ENCODINGS) {
            for (int ch : CHANNELS) {
                for (int rate : RATES) {
                    cases.add(new Case(codec, ch, rate, "default"));
                }
            }
        }
        for (String variant : new String[] {"bext", "id3", "pipe"}) {
            cases.add(new Case("pcm_s16le", 2, 44100, variant));
            cases.add(new Case("pcm_s24le", 6, 48000, variant));
            cases.add(new Case("pcm_f32le", 2, 44100, variant));
        }
        return cases.stream().map(c -> DynamicTest.dynamicTest(c.name(), () -> run(c)));
    }

    // ------------------------------------------------------------------ the case

    private void run(Case c) throws Exception {
        Path wav = dir.resolve(c.file());
        generate(c, wav);

        // READ check
        float[][] reference = ffmpegDecode(wav, c.channels());
        WavFile read = WavReader.read(wav);
        assertEquals(expectedEncoding(c.codec()), read.encoding(), c.name() + " detected encoding");
        assertEquals(c.rate(), read.source().sampleRate(), c.name() + " sample rate");
        float[][] ours = readAll(read.source());
        assertEquals(reference.length, ours.length, c.name() + " channel count");
        assertEquals(reference[0].length, ours[0].length, c.name() + " frame count");
        assertTrue(ours[0].length > c.rate() / 4, c.name() + " suspiciously short: " + ours[0].length);
        compare(c, "read", c.codec(), ours, reference);

        // WRITE check: our file, decoded by the tool
        Path back = dir.resolve("ours-" + c.file());
        WavWriter.write(back, read.source(), read.encoding());
        float[][] decodedOurs = ffmpegDecode(back, c.channels());
        assertEquals(ours[0].length, decodedOurs[0].length, c.name() + " frame count of our file");
        compare(c, "write", c.codec(), ours, decodedOurs);
        if (haveFfprobe) {
            String probe = runTool(dir.resolve("probe.txt"), "ffprobe", "-v", "error", "-select_streams", "a:0",
                    "-show_entries", "stream=codec_name,channels,sample_rate", "-of", "csv=p=0", back.toString())
                    .trim();
            assertEquals(c.codec() + "," + c.rate() + "," + c.channels(), probe, c.name() + " ffprobe of our file");
        }
        if (haveSox) {
            soxCompare(c, wav, ours);
        }
        synchronized (RAN) {
            RAN.add(c.name());
        }
    }

    private void generate(Case c, Path out) throws Exception {
        StringBuilder expr = new StringBuilder("aevalsrc=");
        for (int ch = 0; ch < c.channels(); ch++) {
            if (ch > 0) {
                expr.append('|');
            }
            expr.append("0.8*sin(2*PI*").append(440 + 110 * ch).append("*t)");
        }
        expr.append(":s=").append(c.rate()).append(":d=0.5");
        List<String> cmd = new ArrayList<>(List.of("ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
                "-f", "lavfi", "-i", expr.toString()));
        if (c.variant().equals("bext")) {
            cmd.addAll(List.of("-write_bext", "1"));
        } else if (c.variant().equals("id3")) {
            cmd.addAll(List.of("-write_id3v2", "1"));
        }
        cmd.addAll(List.of("-c:a", c.codec(), "-f", "wav"));
        if (c.variant().equals("pipe")) {
            // stdout is captured to the file; ffmpeg treats pipe: as non-seekable and leaves 0xFFFFFFFF sizes
            cmd.add("pipe:1");
            exec(cmd, out, dir.resolve("gen-err.txt"));
            byte[] head = Files.readAllBytes(out);
            assertEquals(0xFF, head[4] & 0xFF, "pipe output should carry a 0xFFFFFFFF size placeholder");
        } else {
            cmd.add(out.toString());
            exec(cmd, null, dir.resolve("gen-err.txt"));
        }
    }

    /** Decodes with ffmpeg to interleaved float32 and returns planar samples. */
    private float[][] ffmpegDecode(Path wav, int channels) throws Exception {
        Path raw = dir.resolve("dec.raw");
        exec(List.of("ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", "-y", "-i", wav.toString(),
                "-f", "f32le", "-c:a", "pcm_f32le", raw.toString()), null, dir.resolve("dec-err.txt"));
        return planar(Files.readAllBytes(raw), channels);
    }

    private void soxCompare(Case c, Path wav, float[][] ours) {
        try {
            Path raw = dir.resolve("sox.raw");
            exec(List.of("sox", wav.toString(), "-t", "raw", "-e", "floating-point", "-b", "32", "-L",
                    raw.toString()), null, dir.resolve("sox-err.txt"));
            float[][] s = planar(Files.readAllBytes(raw), c.channels());
            double max = 0;
            if (s[0].length != ours[0].length) {
                synchronized (SOX_NOTES) {
                    SOX_NOTES.add(c.name() + ": frame count differs, ours " + ours[0].length + " sox " + s[0].length);
                }
                return;
            }
            for (int ch = 0; ch < ours.length; ch++) {
                for (int i = 0; i < ours[ch].length; i++) {
                    max = Math.max(max, Math.abs(ours[ch][i] - s[ch][i]));
                }
            }
            if (max != 0) {
                synchronized (SOX_NOTES) {
                    SOX_NOTES.add(c.name() + ": max difference " + max);
                }
            }
        } catch (Exception | AssertionError e) {
            synchronized (SOX_NOTES) {
                SOX_NOTES.add(c.name() + ": sox failed: " + e.getMessage());
            }
        }
    }

    // ------------------------------------------------------------------ comparison

    private static void compare(Case c, String stage, String codec, float[][] actual, float[][] expected) {
        boolean tolerant = codec.equals("pcm_s32le");
        double max = 0;
        for (int ch = 0; ch < expected.length; ch++) {
            for (int i = 0; i < expected[ch].length; i++) {
                float a = actual[ch][i];
                float e = expected[ch][i];
                double d = Math.abs((double) a - (double) e);
                max = Math.max(max, d);
                boolean ok = tolerant ? d <= Math.ulp(Math.max(Math.abs(a), Math.abs(e))) : a == e;
                if (!ok) {
                    throw new AssertionError(c.name() + " " + stage + ": first mismatch at channel " + ch
                            + ", frame " + i + ": ours " + a + " (0x" + Integer.toHexString(Float.floatToIntBits(a))
                            + ") vs tool " + e + " (0x" + Integer.toHexString(Float.floatToIntBits(e)) + ")");
                }
            }
        }
        synchronized (MAX_DIFF) {
            MAX_DIFF.merge(codec + " " + stage, max, Math::max);
        }
    }

    private static WavEncoding expectedEncoding(String codec) {
        return switch (codec) {
            case "pcm_u8" -> WavEncoding.PCM_8;
            case "pcm_s16le" -> WavEncoding.PCM_16;
            case "pcm_s24le" -> WavEncoding.PCM_24;
            case "pcm_s32le" -> WavEncoding.PCM_32;
            case "pcm_f32le" -> WavEncoding.FLOAT_32;
            default -> throw new IllegalArgumentException(codec);
        };
    }

    private static float[][] readAll(MemorySampleSource s) {
        float[][] out = new float[s.channelCount()][(int) s.frameCount()];
        s.read(0, (int) s.frameCount(), out, 0);
        return out;
    }

    private static float[][] planar(byte[] raw, int channels) {
        ByteBuffer bb = ByteBuffer.wrap(raw).order(ByteOrder.LITTLE_ENDIAN);
        int frames = raw.length / (4 * channels);
        float[][] out = new float[channels][frames];
        for (int f = 0; f < frames; f++) {
            for (int ch = 0; ch < channels; ch++) {
                out[ch][f] = bb.getFloat();
            }
        }
        return out;
    }

    // ------------------------------------------------------------------ processes

    private static String firstLine(String... cmd) {
        try {
            Process p = new ProcessBuilder(cmd).redirectErrorStream(true).start();
            p.getOutputStream().close();
            String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            if (!p.waitFor(TIMEOUT_SECONDS, TimeUnit.SECONDS)) {
                p.destroyForcibly();
                return null;
            }
            int nl = out.indexOf('\n');
            return nl < 0 ? out.trim() : out.substring(0, nl).trim();
        } catch (IOException | InterruptedException e) {
            return null;
        }
    }

    /** Runs a tool, stdout to {@code stdoutFile} if given, stderr to {@code stderrFile}; fails with stderr. */
    private static void exec(List<String> cmd, Path stdoutFile, Path stderrFile) throws Exception {
        ProcessBuilder pb = new ProcessBuilder(cmd);
        pb.redirectError(stderrFile.toFile());
        if (stdoutFile != null) {
            pb.redirectOutput(stdoutFile.toFile());
        } else {
            pb.redirectOutput(ProcessBuilder.Redirect.DISCARD);
        }
        Process p = pb.start();
        p.getOutputStream().close();
        if (!p.waitFor(TIMEOUT_SECONDS, TimeUnit.SECONDS)) {
            p.destroyForcibly();
            throw new AssertionError(cmd.get(0) + " timed out after " + TIMEOUT_SECONDS + " s: " + cmd);
        }
        if (p.exitValue() != 0) {
            throw new AssertionError(cmd.get(0) + " failed (exit " + p.exitValue() + "): " + cmd + "\n"
                    + Files.readString(stderrFile));
        }
    }

    /** Runs a tool and returns its standard output. */
    private static String runTool(Path stdoutFile, String... cmd) throws Exception {
        Path err = stdoutFile.resolveSibling("tool-err.txt");
        exec(List.of(cmd), stdoutFile, err);
        return Files.readString(stdoutFile);
    }
}
